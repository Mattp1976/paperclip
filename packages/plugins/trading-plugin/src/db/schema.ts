// ─── System Config ──────────────────────────────────────────
export const tradingConfig = pgTable("trading_config", {
  key: varchar("key", { length: 100 }).primaryKey(),
  value: jsonb("value").notNull(),
  description: text("description"),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow(),
});

// ─── Agent Logs ─────────────────────────────────────────────
export const tradingAgentLogs = pgTable(
  "trading_agent_logs",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    agentName: varchar("agent_name", { length: 100 }).notNull(),
    logLevel: varchar("log_level", { length: 10 }).default("info"),
    message: text("message").notNull(),
    context: jsonb("context").default({}),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow(),
  },
  (table) => ({
    timeIdx: index("trading_agent_logs_time").on(table.createdAt),
    agentIdx: index("trading_agent_logs_agent").on(table.agentName, table.createdAt),
  })
);

// ─── Relations ──────────────────────────────────────────────
export const snapshotRelations = relations(tradingSnapshots, ({ one }) => ({
  asset: one(tradingAssets, {
    fields: [tradingSnapshots.assetId],
    references: [tradingAssets.id],
  }),
}));

export const signalRelations = relations(tradingSignals, ({ one }) => ({
  asset: one(tradingAssets, {
    fields: [tradingSignals.assetId],
    references: [tradingAssets.id],
  }),
}));

export const hypothesisRelations = relations(tradingHypotheses, ({ one, many }) => ({
  parent: one(tradingHypotheses, {
    fields: [tradingHypotheses.parentId],
    references: [tradingHypotheses.id],
  }),
  backtestResults: many(tradingBacktestResults),
  paperTrades: many(tradingPaperTrades),
}));

export const backtestRelations = relations(tradingBacktestResults, ({ one }) => ({
  hypothesis: one(tradingHypotheses, {
    fields: [tradingBacktestResults.hypothesisId],
    references: [tradingHypotheses.id],
  }),
}));
